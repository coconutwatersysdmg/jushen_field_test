"""
去现场怎么填（就改下面几个路径）
================================
1. 笔记本网线插现场交换机，IP 设成同网段（1线常见：10.11.206.171）
2. 能打开工控机共享后，把「文件夹」路径填进来（不用管里面照片叫啥名）
3. 保存，重新开软件，点「检查离线路径」

路径两种写法都可以：
  r"\\10.11.206.191\共享名\文件夹"     ← 网络共享
  r"Z:\文件夹"                          ← 先映射成盘符再写

程序会自己进文件夹找 .pcd / 图片，不依赖固定文件名。
"""
from __future__ import annotations

from copy import deepcopy
from pathlib import Path
from typing import Any, Dict

PROJECT_ROOT = Path(__file__).resolve().parents[1]
_DEMO = PROJECT_ROOT.parent / "field_offline_data"  # 本机演示用，现场别用这个

# TODO【现场】确认能访问：梅卡工控机 10.11.206.190（共享账号密码问甲方）
# TODO【现场】确认能访问：雷达电脑   10.11.206.191（共享账号密码问甲方）

OFFLINE_PATHS: Dict[str, Any] = {
    # ------------------------------------------------------------------
    # TODO【必填】雷达数据所在位置
    # 说明：可填「某个 .pcd 文件」，也可填「文件夹」（自动用里面最新的 .pcd）
    # 示例：r"\\10.11.206.191\share\lidar"
    # ------------------------------------------------------------------
    "radar_pcd": str(_DEMO / "radar"),

    # ------------------------------------------------------------------
    # TODO【必填】海康角点照片所在文件夹
    # 说明：只填文件夹，程序自动读取里面的 jpg/png/bmp（不管叫什么名字）
    #       有几张用几张；不够四个角点就循环用；多于四个用时间最早的几张对应 P1..
    # 示例：r"\\10.11.206.190\share\hik\corners"
    # ------------------------------------------------------------------
    "hik_corner_dir": str(_DEMO / "hik"),

    # ------------------------------------------------------------------
    # TODO【选填】梅卡照片所在文件夹（不跑孔位可不管，保持 ""）
    # 说明：填文件夹后自动取里面最新的一张图当彩色；深度同理可另填
    # 示例：r"\\10.11.206.190\share\mech"
    # ------------------------------------------------------------------
    "mech_rgb": str(_DEMO / "mech"),
    "mech_depth": str(_DEMO / "mech"),
    "mech_cloud": "",
}


def get_offline_paths() -> Dict[str, Any]:
    return deepcopy(OFFLINE_PATHS)
